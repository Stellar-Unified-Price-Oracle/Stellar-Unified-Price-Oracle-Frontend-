/// <reference types="vitest" />
import fs from 'fs'
import path from 'path'
import { execFileSync } from 'node:child_process'
import { defineConfig, loadEnv, type Plugin, type ProxyOptions } from 'vite'
import react from '@vitejs/plugin-react'
import tailwindcss from '@tailwindcss/vite'
import { visualizer } from 'rollup-plugin-visualizer'
import { computeReleaseVersion, RELEASE_MANIFEST_FILE } from './src/utils/releaseManifest'

type ProxyConfig = Record<string, ProxyOptions>

/** Declaration in public/sw.js that the build replaces with the release version (#828). */
const SW_VERSION_DECLARATION = "const RELEASE_VERSION = '__RELEASE_VERSION__'"

/**
 * After the bundle and public files are written, derives a release version from
 * the emitted asset list, stamps it into `sw.js` so the service worker's cache is
 * keyed to the files it ships, and writes `release-manifest.json` alongside it.
 */
function releaseManifestPlugin(buildId: string): Plugin {
  let outDir = ''
  return {
    name: 'release-manifest',
    apply: 'build',
    configResolved(config) {
      outDir = path.resolve(config.root, config.build.outDir)
    },
    closeBundle() {
      const swPath = path.join(outDir, 'sw.js')
      if (!fs.existsSync(swPath)) return

      const swSource = fs.readFileSync(swPath, 'utf8')
      if (!swSource.includes(SW_VERSION_DECLARATION)) {
        throw new Error('release-manifest: sw.js is missing the RELEASE_VERSION declaration')
      }

      const assets = fs
        .readdirSync(outDir, { recursive: true })
        .map((entry) => String(entry).split(path.sep).join('/'))
        .filter((entry) => entry !== 'sw.js' && entry !== RELEASE_MANIFEST_FILE)
        .filter((entry) => fs.statSync(path.join(outDir, entry)).isFile())
        .sort()

      const releaseVersion = computeReleaseVersion(buildId, assets)
      fs.writeFileSync(swPath, swSource.replace(SW_VERSION_DECLARATION, `const RELEASE_VERSION = '${releaseVersion}'`))
      fs.writeFileSync(
        path.join(outDir, RELEASE_MANIFEST_FILE),
        `${JSON.stringify({ buildId, releaseVersion, assets }, null, 2)}\n`,
      )
    },
  }
}

/**
 * Load HTTPS certificates for local development.
 *
 * Certificates are generated by `scripts/setup-https.js` using mkcert.
 * If certificates don't exist, this returns undefined and HTTPS is skipped.
 */
function loadHttpsCerts(): { key: string; cert: string } | undefined {
  const certDir = path.resolve(__dirname, '.vite-certs')
  const certFile = path.join(certDir, 'localhost.crt')
  const keyFile = path.join(certDir, 'localhost.key')

  // Return undefined if certificates don't exist (HTTPS will be skipped)
  if (!fs.existsSync(certFile) || !fs.existsSync(keyFile)) {
    return undefined
  }

  return {
    cert: fs.readFileSync(certFile, 'utf-8'),
    key: fs.readFileSync(keyFile, 'utf-8'),
  }
}

/**
 * HTTPS dev-server options, or `undefined` when HTTPS is disabled.
 *
 * Vite's `server.https` option only accepts an `https.ServerOptions` object
 * (a plain `false` is rejected by its types), so the key is conditionally
 * spread only when certificates are actually available.
 */
function resolveHttps(): { key: string; cert: string } | undefined {
  if (process.env.HTTPS !== 'true' && process.env.VITE_HTTPS !== 'true') {
    return undefined
  }
  return loadHttpsCerts()
}

function parseProxyTarget(env: Record<string, string>, envVar: string): ProxyOptions | null {
  const value = env[envVar]
  if (!value) return null
  try {
    return JSON.parse(value) as ProxyOptions
  } catch {
    return { target: value, changeOrigin: true }
  }
}

function buildProxyConfig(env: Record<string, string>): ProxyConfig {
  const proxyConfig: ProxyConfig = {}

  const apiTarget = parseProxyTarget(env, 'VITE_PROXY_API')
  // Trailing slash so only real API paths (/api/prices, /api/version, ...) are
  // proxied — the SPA route /api-docs must reach the frontend, not the backend.
  if (apiTarget) proxyConfig['/api/'] = apiTarget

  const wsTarget = parseProxyTarget(env, 'VITE_PROXY_WS')
  if (wsTarget) proxyConfig['/ws'] = wsTarget

  const prefix = 'VITE_PROXY_'
  for (const [key, value] of Object.entries(env)) {
    if (key.startsWith(prefix) && key !== 'VITE_PROXY_API' && key !== 'VITE_PROXY_WS') {
      const path = '/' + key.slice(prefix.length).toLowerCase().replace(/_/g, '/')
      try {
        proxyConfig[path] = JSON.parse(value) as ProxyOptions
      } catch {
        proxyConfig[path] = { target: value, changeOrigin: true }
      }
    }
  }

  if (Object.keys(proxyConfig).length === 0) {
    proxyConfig['/api/'] = { target: env.VITE_API_URL || 'http://localhost:3000', changeOrigin: true }
    proxyConfig['/ws'] = { target: env.VITE_WS_URL || 'ws://localhost:3000', ws: true }
  }

  return proxyConfig
}

function resolveBuildId(env: Record<string, string>): string {
  const configured = env.VITE_BUILD_COMMIT || env.VERCEL_GIT_COMMIT_SHA || env.GITHUB_SHA
  if (configured) return configured.slice(0, 12)

  try {
    return execFileSync('git', ['rev-parse', '--short=12', 'HEAD'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    }).trim()
  } catch {
    return env.VITE_APP_VERSION || 'development'
  }
}

function resolveAppVersion(env: Record<string, string>): string {
  if (env.VITE_APP_VERSION) return env.VITE_APP_VERSION

  const packageJson: unknown = JSON.parse(fs.readFileSync(path.resolve(__dirname, 'package.json'), 'utf8'))
  if (
    typeof packageJson !== 'object' ||
    packageJson === null ||
    !('version' in packageJson) ||
    typeof packageJson.version !== 'string'
  ) {
    throw new Error('package.json must provide a string version for the PWA update banner')
  }
  return packageJson.version
}

// Hostnames that are always a local/dev default, never a real third-party
// origin worth a preconnect/dns-prefetch hint (#509). Guards against emitting
// hints for `http://localhost:3000`-style fallbacks when VITE_API_URL /
// VITE_WS_URL aren't actually configured for this build.
const DEV_DEFAULT_HOSTS = new Set(['localhost', '127.0.0.1', '0.0.0.0', '::1'])

function isKnownProductionOrigin(rawUrl: string | undefined): string | null {
  if (!rawUrl) return null
  try {
    const url = new URL(rawUrl.replace(/^ws:/, 'http:').replace(/^wss:/, 'https:'))
    if (DEV_DEFAULT_HOSTS.has(url.hostname)) return null
    return url.origin
  } catch {
    return null
  }
}

export default defineConfig(({ mode }) => {
  const env = loadEnv(mode, process.cwd(), '')
  const proxyConfig = buildProxyConfig(env)
  const buildId = resolveBuildId(env)
  const appVersion = resolveAppVersion(env)

  const httpsOptions = resolveHttps()

  // Resource hints are only emitted for explicitly configured production
  // origins — not the localhost fallbacks used in local dev — so preview/dev
  // builds without real API/WS origins don't ship dead preconnect hints.
  const origins = new Set<string>()

  const apiOrigin = isKnownProductionOrigin(env.VITE_API_URL)
  if (apiOrigin) origins.add(apiOrigin)

  const wsOrigin = isKnownProductionOrigin(env.VITE_WS_URL)
  if (wsOrigin) origins.add(wsOrigin)

  const hints = Array.from(origins)
    .flatMap((origin) => [`<link rel="preconnect" href="${origin}" />`, `<link rel="dns-prefetch" href="${origin}" />`])
    .join('\n    ')

  return {
    define: {
      __APP_BUILD_ID__: JSON.stringify(buildId),
      __APP_VERSION__: JSON.stringify(appVersion),
    },
    plugins: [
      react(),
      tailwindcss(),
      releaseManifestPlugin(buildId),
      {
        name: 'resource-hints',
        transformIndexHtml: {
          order: 'post',
          handler(html: string) {
            return hints ? html.replace('<!-- __RESOURCE_HINTS__ -->', hints) : html
          },
        },
      },
      {
        name: 'preload-critical-assets',
        transformIndexHtml: {
          order: 'post',
          handler(html: string) {
            const jsMatch = html.match(/<script\s+type="module"[^>]*src="([^"]+)"[^>]*><\/script>/)
            const cssMatch = html.match(/<link\s+rel="stylesheet"[^>]*href="((?!https?:\/\/)[^"]+)"[^>]*>/)

            const preloads: string[] = []

            if (cssMatch) {
              preloads.push(`<link rel="preload" as="style" href="${cssMatch[1]}" crossorigin />`)
            }

            if (jsMatch) {
              preloads.push(`<link rel="modulepreload" href="${jsMatch[1]}" crossorigin />`)
            }

            if (preloads.length === 0) return html

            return html.replace('</title>', `</title>\n    ${preloads.join('\n    ')}`)
          },
        },
      },
      ...(process.env.ANALYZE === 'true'
        ? [
            visualizer({
              filename: 'reports/bundle-analysis.html',
              open: false,
              gzipSize: true,
              brotliSize: true,
            }),
          ]
        : []),
    ],
    // Served at the domain root: Vercel is the only deploy target in CI (no
    // GitHub Pages workflow exists), and the preview server used by Playwright
    // E2E/visual tests must serve bare paths like /dashboard directly.
    base: '/',
    build: {
      // Generate hidden source maps (not inlined into JS — kept as separate .map files).
      // These are NOT uploaded to the CDN/static host; a post-build CI step strips them
      // from the deployment artifact and uploads them to the error-tracking service
      // (Sentry) instead.  See docs/source-maps.md for the full strategy.
      sourcemap: mode === 'production' ? 'hidden' : true,
      rollupOptions: {
        output: {
          entryFileNames: 'assets/[name]-[hash].js',
          chunkFileNames: 'assets/[name]-[hash].js',
          assetFileNames: 'assets/[name]-[hash][extname]',
          manualChunks(id) {
            const moduleId = id.replace(/\\/g, '/')

            if (moduleId.includes('/node_modules/')) {
              if (
                moduleId.includes('/react/') ||
                moduleId.includes('/react-dom/') ||
                moduleId.includes('/react-router') ||
                moduleId.includes('/scheduler/')
              ) {
                return 'vendor-react'
              }
              if (moduleId.includes('/@tanstack/react-virtual/')) {
                return 'vendor-tables'
              }
              if (
                moduleId.includes('/i18next/') ||
                moduleId.includes('/react-i18next/') ||
                moduleId.includes('/i18next-browser-languagedetector/')
              ) {
                return 'vendor-i18n'
              }
              if (moduleId.includes('/@tanstack/react-query/')) {
                return 'vendor-data'
              }
              if (moduleId.includes('/comlink/')) {
                return 'vendor-workers'
              }
              if (moduleId.includes('/@stellar/')) {
                return 'vendor-stellar'
              }
              if (moduleId.includes('/zod/')) {
                return 'vendor-validation'
              }
            }

            return undefined
          },
        },
      },
    },
    server: {
      port: 5173,
      proxy: proxyConfig,
      /**
       * Hot Module Replacement configuration for faster, more reliable development
       *
       * Key optimizations:
       * 1. Direct protocol (ws/wss) instead of fallback to long-polling
       * 2. Shorter reconnect delays for faster feedback loops
       * 3. Full reload fallback when HMR fails (prevents stale state)
       * 4. Increased timeout to handle slow networks
       */
      hmr: {
        protocol: 'ws',
        host: 'localhost',
        port: 5173,
        timeout: 10_000, // 10 seconds before full reload fallback
      },
      /**
       * HTTPS support for local development.
       *
       * Service Workers, geolocation, and some WebSocket features require HTTPS.
       * Certificates are auto-generated by `scripts/setup-https.js` using mkcert.
       *
       * Enable HTTPS:
       *   npm run dev:https
       *   HTTPS=true npm run dev
       *   VITE_HTTPS=true npm run dev
       *
       * If certificates don't exist, HTTP is used (graceful fallback).
       */
      ...(httpsOptions ? { https: httpsOptions } : {}),
    },
  }
})
